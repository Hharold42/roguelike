/**
 * Общие константы софтверной графики: дальность, палитра, дизеринг Байера,
 * таблица тумана. Вынесены из renderer.ts, чтобы слои поверх мира
 * (grass.ts — колоски травы) квантовали цвета и туман точно так же.
 */

export const Z_FAR = 170; // дальше — сплошной туман
export const LEVELS = 6; // градаций на канал

// Матрица Байера 4×4
export const BAYER = new Float32Array([0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => (v + 0.5) / 16));

const FOG_K = 0.016;

// Туман — таблица, чтобы не звать exp в горячем цикле
export const FOG_LUT = new Float32Array(512);
for (let i = 0; i < 512; i++) {
  const z = (i / 511) * Z_FAR * FOG_K;
  FOG_LUT[i] = 1 - Math.exp(-z * z);
}
